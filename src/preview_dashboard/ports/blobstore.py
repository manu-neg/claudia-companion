"""BlobStore port: content-addressed-by-id storage of file bytes.

Blob ids are generated by the store, never taken from the caller, so
nothing user-supplied ever becomes a storage path (docs/security.md C7,
C20, C25). Contract is enforced by `tests/contracts/blob_store.py`.

Security obligations for every implementation (filesystem or otherwise):
- **Validate before use:** every `blob_id` argument is checked as a
  canonical ULID (`domain.models.is_ulid`) *before* any path, key or query
  is built from it; a malformed id behaves exactly like an unknown one.
- **Never follow symlinks:** a symlinked store root / blob directory is
  refused (fail at construction), and blobs are opened with `O_NOFOLLOW`
  (a symlink in place of a blob is "not found", never dereferenced).
- **Only complete, canonical blobs are visible:** staging/temporary files
  never appear in `open` or `list_ids`.
- **Orphan-sweep protocol** (see `ports.repository` and
  docs/architecture.md): the sweep first snapshots
  `list_ids(created_before=now - grace)`, *then* reads
  `ItemRepository.all_blob_ids()`, and deletes only ids in the first set
  but not the second. `grace` must exceed the application's hard publish
  timeout, so a blob whose DB row is still being committed is never swept.
"""

from __future__ import annotations

from collections.abc import Iterable
from datetime import datetime
from typing import BinaryIO, Protocol

from preview_dashboard.domain.models import BlobRef


class BlobStore(Protocol):
    """Stores immutable byte blobs under generated ids."""

    def put(self, chunks: Iterable[bytes], max_bytes: int) -> BlobRef:
        """Store the concatenation of `chunks` as a new blob.

        The blob becomes visible (in `open`/`list_ids`) only once complete;
        on any error nothing partial is left behind (no blob, no staging
        file, no space consumed).

        Args:
            chunks: byte chunks, consumed once, in order.
            max_bytes: upper bound on the total size (>= 0), inclusive.

        Returns:
            BlobRef with the new id, byte size and SHA-256 hex digest.

        Raises:
            LimitExceededError: more than `max_bytes` bytes were supplied
                (raised as soon as the limit is crossed), or the backing
                storage ran out of space (disk full / ENOSPC / quota) —
                in both cases nothing is left behind.
            ValueError: `max_bytes` is negative (programming error).
            Any exception raised by `chunks` propagates unchanged.
        """
        ...

    def open(self, blob_id: str) -> BinaryIO:
        """Open a blob for reading; the stream is seekable (for HTTP Range).

        `blob_id` is validated before any path is built, and the blob is
        opened without following symlinks. The caller must close the stream.

        Raises:
            NotFoundError: unknown or malformed blob id (including traversal
                attempts such as `../x`, absolute paths, lowercase or
                overlong ULIDs), or a non-regular / symlinked blob file.
        """
        ...

    def delete(self, blob_id: str) -> None:
        """Delete a blob; idempotent (unknown or malformed ids are ignored).

        A malformed id never reaches the storage layer, so nothing outside
        the store (or any staging file) can be deleted through this method.
        """
        ...

    def list_ids(self, created_before: datetime | None = None) -> set[str]:
        """Return ids of all complete, canonical-ULID blobs (never staging files).

        Args:
            created_before: if given (tz-aware), only blobs stored strictly
                before this instant. "Stored" is the moment `put` made the
                blob visible, measured by the store's injected `Clock` (the
                same clock the application uses for `now`) or, for stores
                that only have filesystem timestamps, the file's mtime —
                which must be taken from the same host clock. The orphan
                sweep uses it as a grace period (see module docstring).
        """
        ...

    def free_bytes(self) -> int:
        """Return the bytes still available for new blobs (>= 0)."""
        ...
